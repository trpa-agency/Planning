"""Build a test geodatabase for fix_district_geometry.py from the public services.

District comes from Zoning/MapServer/0 in EPSG 26910 with ACRES, gets GlobalIDs, and has
030 and 040 renamed to WCTAP_030 and WCTAP_040 to match the edit version after E04. A
Parcel layer holds parcel 032-141-018 from LocalPlan/MapServer/0. Writes
data/test/geometry_test.gdb and tests/geometry_test_config.yaml.

    python tests/build_geometry_test_gdb.py
"""

from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import arcpy
import yaml

ROOT = Path(__file__).resolve().parents[1]
GDB_DIR = ROOT / "data" / "test"
GDB = GDB_DIR / "geometry_test.gdb"
BASE = "https://maps.trpa.org/server/rest/services"


def to_fc(url: str, where: str, fields: str, name: str) -> str:
    q = urllib.parse.urlencode({"where": where, "outFields": fields, "outSR": 26910, "resultRecordCount": 2000, "f": "json"})
    with urllib.request.urlopen(f"{url}/query?{q}", timeout=120) as response:
        data = json.load(response)
    path = GDB_DIR / f"{name}.json"
    path.write_text(json.dumps(data), encoding="utf-8")
    out = str(GDB / name)
    arcpy.conversion.JSONToFeatures(str(path), out)
    path.unlink()
    return out


def main() -> int:
    arcpy.env.overwriteOutput = True
    GDB_DIR.mkdir(parents=True, exist_ok=True)
    if arcpy.Exists(str(GDB)):
        arcpy.management.Delete(str(GDB))
    arcpy.management.CreateFileGDB(str(GDB_DIR), GDB.name)

    district = to_fc(f"{BASE}/Zoning/MapServer/0", "1=1", "ZONING_ID,PLAN_ID,ACRES", "District")
    arcpy.management.AddGlobalIDs(district)
    with arcpy.da.UpdateCursor(district, ["ZONING_ID"], "ZONING_ID IN ('030', '040')") as cursor:
        for (zid,) in cursor:
            cursor.updateRow(["WCTAP_" + zid])
    to_fc(f"{BASE}/LocalPlan/MapServer/0", "APN = '032-141-018'", "APN", "Parcel")

    config = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    config["sde"]["connection"] = str(GDB).replace("\\", "/")
    config["sde"]["edit_version"] = "local test"
    config["datasets"] = {"district": "District", "permissible_uses": None, "special_designation": None,
                          "parcel": "Parcel", "local_plan_parcels": None}
    for key in ("snapshots", "outputs", "logs"):
        config["paths"][key] = f"data/test/{key}"
    (ROOT / "tests" / "geometry_test_config.yaml").write_text(
        "# Generated by tests/build_geometry_test_gdb.py.\n" + yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    print(f"Built {GDB}: {arcpy.management.GetCount(district)[0]} districts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
