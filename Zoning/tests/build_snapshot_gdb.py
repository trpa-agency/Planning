"""Build a test geodatabase from the 2026-11-20 service snapshot, keeping the real GlobalIDs.

Used to test rebuild_fixes.py: the fix package was built from this state, so against it
every fix row should be pending. Writes data/test/snapshot_test.gdb (District with null
shapes, PermissibleUses, Special_Designation; GlobalID as a text field) and
tests/snapshot_test_config.yaml pointed at it.

    python tests/build_snapshot_gdb.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import arcpy
import yaml

ROOT = Path(__file__).resolve().parents[1]
SNAP = ROOT / "data" / "raw" / "snapshot_2026-11-20"
GDB_DIR = ROOT / "data" / "test"
GDB = GDB_DIR / "snapshot_test.gdb"


def records(name: str) -> list[dict]:
    data = json.loads((SNAP / name).read_text(encoding="utf-8"))
    rows = data["features"] if isinstance(data, dict) else data
    return [r.get("attributes", r) for r in rows]


def build(name: str, rows: list[dict], fields: list[str], geometry: bool) -> None:
    path = str(GDB / name)
    if geometry:
        arcpy.management.CreateFeatureclass(str(GDB), name, "POLYGON", spatial_reference=26910)
    else:
        arcpy.management.CreateTable(str(GDB), name)
    for field in ["GlobalID", *fields]:
        arcpy.management.AddField(path, field, "TEXT", field_length=2000)
    cols = ["GlobalID", *fields] + (["SHAPE@"] if geometry else [])
    with arcpy.da.InsertCursor(path, cols) as cursor:
        for r in rows:
            values = [None if r.get(f) is None else str(r.get(f)) for f in ["GlobalID", *fields]]
            cursor.insertRow(values + ([None] if geometry else []))
    print(f"{name}: {len(rows)} rows")


def main() -> int:
    arcpy.env.overwriteOutput = True
    GDB_DIR.mkdir(parents=True, exist_ok=True)
    if arcpy.Exists(str(GDB)):
        arcpy.management.Delete(str(GDB))
    arcpy.management.CreateFileGDB(str(GDB_DIR), GDB.name)

    build("District", records("district_attr.json"), ["ZONING_ID", "PLAN_ID", "ZONING_DESCRIPTION"], True)
    build("PermissibleUses", records("permissible_use.json"),
          ["Zoning_ID", "Category", "Subcategory", "Use_Type", "Use_Status", "Density", "Unit", "Notes"], False)
    build("Special_Designation", records("special_designation.json"),
          ["ZONING_ID", "ZONING_DESCRIPTION", "SPECIAL_DESIGNATION"], False)

    config = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    config["sde"]["connection"] = str(GDB).replace("\\", "/")
    config["sde"]["edit_version"] = "local test"
    config["datasets"] = {
        "district": "District", "permissible_uses": "PermissibleUses",
        "special_designation": "Special_Designation", "parcel": None, "local_plan_parcels": None,
    }
    # The fixed server targets do not apply to the 2026-11-20 state; use computed counts only.
    config.setdefault("post_tables", {})["expected_counts"] = None
    for key in ("snapshots", "outputs", "logs"):
        config["paths"][key] = f"data/test/{key}"
    (ROOT / "tests" / "snapshot_test_config.yaml").write_text(
        "# Generated by tests/build_snapshot_gdb.py.\n" + yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
