"""Build a local test geodatabase that mimics the SDE zoning schema for script tests.

Pulls District features (EPSG 26910) and the related Permissible Use and Special
Designation rows for a few districts from the public Zoning service, adds GlobalIDs and
simple relationship classes keyed on ZONING_ID, and plants a duplicate copy of the 035
shape. Writes data/test/zoning_test.gdb and tests/test_config.yaml pointed at it.

    python tests/build_test_gdb.py
"""

from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import arcpy
import yaml

ROOT = Path(__file__).resolve().parents[1]
SERVICE = "https://maps.trpa.org/server/rest/services/Zoning/MapServer"
TEST_IDS = ["035", "035_SA1", "032B", "045", "055", "056"]
GDB_DIR = ROOT / "data" / "test"
GDB = GDB_DIR / "zoning_test.gdb"


def query(layer: int, where: str, fields: str, geometry: bool) -> dict:
    params = {
        "where": where, "outFields": fields, "returnGeometry": str(geometry).lower(),
        "outSR": 26910, "resultRecordCount": 2000, "f": "json",
    }
    url = f"{SERVICE}/{layer}/query?{urllib.parse.urlencode(params)}"
    with urllib.request.urlopen(url, timeout=120) as response:
        return json.load(response)


def build_table(name: str, layer: int, key: str, extra: list[str]) -> str:
    path = str(GDB / name)
    arcpy.management.CreateTable(str(GDB), name)
    for field in [key, *extra]:
        arcpy.management.AddField(path, field, "TEXT", field_length=255)
    ids = ", ".join(f"'{z}'" for z in TEST_IDS)
    data = query(layer, f"{key} IN ({ids})", ",".join([key, *extra]), False)
    with arcpy.da.InsertCursor(path, [key, *extra]) as cursor:
        for feature in data["features"]:
            cursor.insertRow([feature["attributes"].get(f) for f in [key, *extra]])
    arcpy.management.AddGlobalIDs(path)
    return path


def main() -> int:
    arcpy.env.overwriteOutput = True
    GDB_DIR.mkdir(parents=True, exist_ok=True)
    if arcpy.Exists(str(GDB)):
        arcpy.management.Delete(str(GDB))
    arcpy.management.CreateFileGDB(str(GDB_DIR), GDB.name)

    data = query(0, "1=1", "ZONING_ID,PLAN_ID,ZONING_DESCRIPTION", True)
    json_path = GDB_DIR / "district.json"
    json_path.write_text(json.dumps(data), encoding="utf-8")
    district = str(GDB / "District")
    arcpy.conversion.JSONToFeatures(str(json_path), district)
    json_path.unlink()

    with arcpy.da.SearchCursor(district, ["SHAPE@", "ZONING_ID", "PLAN_ID", "ZONING_DESCRIPTION"], "ZONING_ID = '035'") as cursor:
        original = next(cursor)
    with arcpy.da.InsertCursor(district, ["SHAPE@", "ZONING_ID", "PLAN_ID", "ZONING_DESCRIPTION"]) as cursor:
        dup_oid = cursor.insertRow(original)
    keep_oid = [r[0] for r in arcpy.da.SearchCursor(district, ["OID@"], "ZONING_ID = '035'") if r[0] != dup_oid][0]
    arcpy.management.AddGlobalIDs(district)

    pu = build_table("PermissibleUses", 6, "Zoning_ID", ["Category", "Use_Type", "Use_Status"])
    sd = build_table("Special_Designation", 7, "ZONING_ID", ["SPECIAL_DESIGNATION"])
    for table, key, name in ((pu, "Zoning_ID", "District_PermissibleUses"),
                             (sd, "ZONING_ID", "District_SpecialDesignation")):
        arcpy.management.CreateRelationshipClass(
            district, table, str(GDB / name), "SIMPLE", "Uses", "District", "NONE",
            "ONE_TO_MANY", "NONE", "ZONING_ID", key,
        )

    config = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    config["sde"]["connection"] = str(GDB).replace("\\", "/")
    config["sde"]["edit_version"] = "local test"
    config["datasets"] = {
        "district": "District",
        "permissible_uses": "PermissibleUses",
        "special_designation": "Special_Designation",
        "parcel": None,
        "local_plan_parcels": None,
    }
    config["paths"]["snapshots"] = "data/test/snapshots"
    config["paths"]["outputs"] = "data/test/outputs"
    config["paths"]["logs"] = "data/test/logs"
    config["e03"]["delete_objectid"] = dup_oid
    config["e03"]["keep_objectid"] = keep_oid
    (ROOT / "tests" / "test_config.yaml").write_text(
        "# Generated by tests/build_test_gdb.py. Points the scripts at the local test geodatabase.\n"
        + yaml.safe_dump(config, sort_keys=False), encoding="utf-8",
    )
    print(f"Built {GDB}: keep OBJECTID {keep_oid}, duplicate OBJECTID {dup_oid}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
